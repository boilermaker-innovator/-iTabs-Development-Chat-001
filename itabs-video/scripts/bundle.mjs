// Builds dist/worker.js: ONE file with everything inside, for pasting into the
// Cloudflare dashboard code editor (no terminal needed).
import { build } from "esbuild";
await build({
  entryPoints: ["src/worker.js"],
  bundle: true,
  format: "esm",
  target: "es2022",
  loader: { ".html": "text" },
  outfile: "dist/worker.js",
  banner: { js: "// iTabs This Video: single-file build. Generated by `npm run bundle` from src/. Paste this whole file into the Cloudflare editor." },
});
console.log("Wrote dist/worker.js");
